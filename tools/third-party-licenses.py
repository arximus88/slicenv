#!/usr/bin/env python3
"""Ліцензії Rust-залежностей, що потрапляють у бінарники slicenv і slicenv-mcp.

cargo-about не потрібен: беремо `cargo metadata` (Linux x86_64, лише normal-залежності,
бо dev- і build-залежності в бінарник не лінкуються) і обходимо граф від крейтів `app`
та `mcp`.

  tools/third-party-licenses.py --markdown packaging/THIRD-PARTY-RUST-CRATES.md
  tools/third-party-licenses.py --texts dist/THIRD-PARTY-LICENSES.txt

`--texts` додає повні тексти LICENSE*/COPYING*/NOTICE* з каталогу кожного крейта
(для архівів і пакетів: MIT/BSD/Apache вимагають постачати копірайт разом із бінарником).
"""
import argparse
import json
import pathlib
import subprocess
import sys
from collections import defaultdict

ROOTS = ("app", "mcp")
LICENSE_GLOBS = ("LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "UNLICENSE*")


def metadata(target: str) -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def shipped(meta: dict) -> list[dict]:
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    start = [pid for pid in workspace if packages[pid]["name"] in ROOTS]
    seen, stack = set(), list(start)
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return sorted(
        (packages[p] for p in seen if p not in workspace),
        key=lambda p: (p["name"], p["version"]),
    )


def license_files(pkg: dict) -> list[pathlib.Path]:
    root = pathlib.Path(pkg["manifest_path"]).parent
    files = set()
    for pattern in LICENSE_GLOBS:
        files.update(p for p in root.glob(pattern) if p.is_file())
    if pkg.get("license_file"):
        extra = root / pkg["license_file"]
        if extra.is_file():
            files.add(extra)
    return sorted(files)


def write_markdown(pkgs: list[dict], path: pathlib.Path) -> None:
    by_license = defaultdict(list)
    for p in pkgs:
        by_license[p.get("license") or "(не вказано в Cargo.toml)"].append(p)
    lines = [
        "# Rust-залежності у бінарниках Slicenv",
        "",
        "Згенеровано `tools/third-party-licenses.py` з `cargo metadata --locked` для",
        "x86_64-unknown-linux-gnu: лише normal-залежності крейтів `app` (slicenv) і `mcp`",
        "(slicenv-mcp). Не редагувати вручну — перегенерувати після зміни Cargo.lock.",
        "Повні тексти ліцензій постачаються в пакетах як `THIRD-PARTY-LICENSES.txt`.",
        "",
        f"Усього крейтів: {len(pkgs)}.",
        "",
        "## Зведення за ліцензіями",
        "",
        "| Ліцензія (SPDX) | Крейтів |",
        "|---|---|",
    ]
    for lic, items in sorted(by_license.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines.append(f"| `{lic}` | {len(items)} |")
    lines += ["", "## Перелік", "", "| Крейт | Версія | Ліцензія | Джерело |", "|---|---|---|---|"]
    for p in pkgs:
        src = p.get("repository") or ("crates.io" if (p.get("source") or "").startswith("registry") else p.get("source") or "")
        lines.append(f"| {p['name']} | {p['version']} | `{p.get('license') or '—'}` | {src} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_texts(pkgs: list[dict], path: pathlib.Path) -> int:
    missing = 0
    with path.open("w", encoding="utf-8") as out:
        out.write("Third-party licenses of Rust crates linked into slicenv and slicenv-mcp.\n")
        out.write("Generated by tools/third-party-licenses.py from Cargo.lock.\n\n")
        for p in pkgs:
            out.write("=" * 78 + "\n")
            out.write(f"{p['name']} {p['version']} — {p.get('license') or 'unknown'}\n")
            if p.get("repository"):
                out.write(f"{p['repository']}\n")
            out.write("=" * 78 + "\n\n")
            files = license_files(p)
            if not files:
                missing += 1
                out.write(f"(no license file in the crate package; SPDX: {p.get('license')})\n\n")
            for f in files:
                out.write(f"--- {f.name} ---\n")
                out.write(f.read_text(encoding="utf-8", errors="replace").rstrip() + "\n\n")
    return missing


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown", type=pathlib.Path)
    ap.add_argument("--texts", type=pathlib.Path)
    ap.add_argument("--target", default="x86_64-unknown-linux-gnu")
    args = ap.parse_args()
    pkgs = shipped(metadata(args.target))
    if args.markdown:
        write_markdown(pkgs, args.markdown)
    if args.texts:
        missing = write_texts(pkgs, args.texts)
        print(f"{len(pkgs)} crates, {missing} without a license file", file=sys.stderr)
    if not (args.markdown or args.texts):
        for p in pkgs:
            print(f"{p['name']}\t{p['version']}\t{p.get('license')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
